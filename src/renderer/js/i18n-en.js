  // ---------- Motor
  const norm = (s) => String(s).replace(/\s+/g, ' ').trim();
  const escRe = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const exact = new Map(Object.entries(EXACT).map(([k, v]) => [norm(k), v]));
  const compiled = PATTERNS.map(([es, en]) => {
    const parts = es.split(/(\{#?\d\})/);
    const order = [];
    const src = parts.map((p) => {
      // {0} admite cualquier texto; {#0} solo números
      const m = p.match(/^\{(#?)(\d)\}$/);
      if (m) { order.push(Number(m[2])); return m[1] ? '([\\d.,]+)' : '(.+?)'; }
      return escRe(p);
    }).join('');
    // Las plantillas con más texto fijo se prueban primero (son más específicas)
    return { re: new RegExp(`^${src}$`, 's'), order, en, weight: es.replace(/\{#?\d\}/g, '').length, dot: es.includes(' · ') };
  }).sort((a, b) => b.weight - a.weight);

  function translate(text, depth = 0) {
    if (text == null) return null;
    const key = norm(text);
    if (!key || !/[A-Za-zÁÉÍÓÚáéíóúÑñ¿¡]/.test(key)) return null;
    const hit = exact.get(key);
    if (hit !== undefined) return hit;
    if (depth > 3) return null;
    const tryPatterns = (onlyDot) => {
      for (const p of compiled) {
        if (onlyDot && !p.dot) continue;
        const m = key.match(p.re);
        if (!m) continue;
        let out = p.en;
        p.order.forEach((idx, i) => {
          const val = m[i + 1];
          const tr = translate(val, depth + 1);
          out = out.split(`{${idx}}`).join(tr != null ? tr : val);
        });
        return out;
      }
      return null;
    };
    // Une las partes traducidas; null si ninguna parte cambió
    const bySegments = (segs, sep) => {
      let changed = false;
      const out = segs.map((s) => {
        const tr = translate(s, depth + 1);
        if (tr != null) { changed = true; return tr; }
        return s;
      });
      return changed ? out.join(sep) : null;
    };
    // Con «·» primero se prueban las plantillas que lo incluyen y luego parte por parte
    // (los nombres de modelos también usan «·», por eso al final se prueban todas)
    const hasDot = key.includes(' · ');
    let res = tryPatterns(hasDot);
    if (res == null && hasDot) res = bySegments(key.split(' · '), ' · ');
    if (res == null && hasDot) res = tryPatterns(false);
    // Varias oraciones juntas: se traduce cada una
    if (res == null) {
      const sentences = key.split(/(?<=[.!?])\s+(?=[A-ZÁÉÍÓÚÑ¿¡«])/);
      if (sentences.length > 1) res = bySegments(sentences, ' ');
    }
    return res;
  }

